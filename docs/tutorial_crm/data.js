/* Locale-correct formatting. VN groups thousands with "." and decimals with ",". */
function money(n, lang) {
  const s = Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, lang === "vi" ? "." : ",");
  return s + " ₫";
}
function pct(n, lang) {
  return (lang === "vi" ? n.toFixed(1).replace(".", ",") : n.toFixed(1)) + "%";
}
function num(n, lang) {
  return n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, lang === "vi" ? "." : ",");
}

