def replace_terms(text):
    parts = []
    position = 0
    for match in base.base.PROTECTED_RE.finditer(text):
        segment = text[position : match.start()]
        for old, new in REPLACEMENTS:
            segment = segment.replace(old, new)
        parts.extend((segment, match.group(0)))
        position = match.end()
    segment = text[position:]
    for old, new in REPLACEMENTS:
        segment = segment.replace(old, new)
    parts.append(segment)
    return "".join(parts)


def review_translation(text):
    text = base.review_translation(text)
    parts = base.base.TAG_RE.split(text)
    for index, part in enumerate(parts):
        if not base.base.TAG_RE.fullmatch(part or ""):
            parts[index] = replace_terms(part)
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mapping", type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()

    mapping = base.base.load_mapping(args.mapping)
    reviewed = {
        msgid: OVERRIDES.get(
            msgid,
            base.OVERRIDES.get(
                msgid,
                base.base.OVERRIDES.get(msgid, review_translation(msgstr)),
            ),
        )
        for msgid, msgstr in mapping.items()
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(reviewed, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Reviewed {len(reviewed)} translations in {args.output}")


if __name__ == "__main__":
    main()
